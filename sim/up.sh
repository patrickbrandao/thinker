#!/usr/bin/env bash
# Simulation (docs/dev/simulacao-pura.md): brings every piece up. Thinker runs
# exactly as in production; only its accounts point at the White Wizard mocks.
# Idempotent: what is already up stays up.
set -euo pipefail
. "$(dirname "$0")/lib.sh"

for b in wwz wwz-load wwz-tools; do
  [ -x "$WWZ_BIN/$b" ] || die "missing $WWZ_BIN/$b (cd $WWZ_REPO && go build -o bin/ ./cmd/wwz ./cmd/wwz-load ./cmd/wwz-tools), or set WWZ_REPO"
done
command -v docker >/dev/null || die "docker is required (Postgres container $SIM_PG_CONTAINER)"
mkdir -p "$STATE/logs" "$STATE/pids" "$STATE/rec" "$STATE/agents"

# 1. Environment (once; random local secrets).
if [ ! -f "$STATE/env" ]; then
  pg_pass="$(openssl rand -hex 16)"
  db="postgresql://thinker:$pg_pass@127.0.0.1:$SIM_PG_PORT/thinker_sim"
  cat >"$STATE/env" <<ENV
# Generated by sim/up.sh. Local, disposable secrets.
NODE_ENV=development
PORT=$SIM_API_PORT
BIND_ADDRESS=127.0.0.1
BETTER_AUTH_URL=$SIM_API
CORS_ORIGIN=http://127.0.0.1:$SIM_WEB_PORT
SIM_PG_PASSWORD=$pg_pass
DATABASE_URL=$db
MIGRATION_DATABASE_URL=$db
DATABASE_UNPOOLED_URL=$db
BETTER_AUTH_SECRET=$(openssl rand -hex 32)
THINKER_ENCRYPTION_KEY=$(openssl rand -hex 32)
THINKER_SETUP_TOKEN=$(openssl rand -hex 24)
THINKER_RECORDING_STORAGE=filesystem
THINKER_RECORDING_FILESYSTEM_PATH=$STATE/rec
MCP_ENABLED=false
ENV
  chmod 600 "$STATE/env"
  log "wrote sim/.state/env"
fi
# Older sim/.state/env files carried the removed simulation-mode variables.
if grep -q '^THINKER_SIM' "$STATE/env"; then
  grep -v '^THINKER_SIM\|^THINKER_CATALOG_SYNC=' "$STATE/env" >"$STATE/env.tmp" && mv "$STATE/env.tmp" "$STATE/env"
  chmod 600 "$STATE/env"
  log "removed old simulation-mode variables from sim/.state/env"
fi
load_env

# 2. Simulated providers.
start_bg wwz-opencode "$SIM_WWZ_OPENCODE_PORT" "$SIM_DIR" "$WWZ_BIN/wwz" serve -config "$SIM_DIR/wwz/opencode.yaml"
start_bg wwz-openai "$SIM_WWZ_OPENAI_PORT" "$SIM_DIR" "$WWZ_BIN/wwz" serve -config "$SIM_DIR/wwz/openai.yaml"
wait_port "$SIM_WWZ_OPENCODE_PORT" 20 wwz-opencode
wait_port "$SIM_WWZ_OPENAI_PORT" 20 wwz-openai

# 3. PostgreSQL (data kept in the $SIM_PG_VOLUME volume).
if docker ps --format '{{.Names}}' | grep -qx "$SIM_PG_CONTAINER"; then
  log "$SIM_PG_CONTAINER already up on $SIM_PG_PORT"
elif docker ps -a --format '{{.Names}}' | grep -qx "$SIM_PG_CONTAINER"; then
  docker start "$SIM_PG_CONTAINER" >/dev/null
  log "$SIM_PG_CONTAINER started"
else
  docker run -d --name "$SIM_PG_CONTAINER" -p "127.0.0.1:$SIM_PG_PORT:5432" \
    -e POSTGRES_USER=thinker -e POSTGRES_PASSWORD="$SIM_PG_PASSWORD" -e POSTGRES_DB=thinker_sim \
    -v "$SIM_PG_VOLUME:/var/lib/postgresql" "$SIM_PG_IMAGE" >/dev/null
  log "$SIM_PG_CONTAINER created on $SIM_PG_PORT"
fi
i=0
until docker exec "$SIM_PG_CONTAINER" pg_isready -U thinker -d thinker_sim >/dev/null 2>&1; do
  i=$((i + 1)); [ "$i" -lt 30 ] || die "Postgres did not get ready"; sleep 1
done

# 4. Thinker backend (built from this checkout) and dashboard.
if port_up "$SIM_API_PORT"; then
  log "backend already up on $SIM_API_PORT"
else
  if [ "${SIM_SKIP_BUILD:-}" != "1" ]; then
    log "building shared and backend..."
    (cd "$REPO_DIR" && npm run build --workspace=thinker-shared >"$STATE/logs/build.log" 2>&1 \
      && npm run build --workspace=thinker-backend >>"$STATE/logs/build.log" 2>&1) \
      || die "build failed (sim/.state/logs/build.log)"
  fi
  start_bg backend "$SIM_API_PORT" "$REPO_DIR/packages/backend" node dist/main
fi
wait_http "$SIM_API/api/v1/health" 120 backend
start_bg web "$SIM_WEB_PORT" "$REPO_DIR/packages/frontend" env VITE_BACKEND_PORT="$SIM_API_PORT" \
  "$REPO_DIR/node_modules/.bin/vite" --host 127.0.0.1 --port "$SIM_WEB_PORT" --strictPort
wait_port "$SIM_WEB_PORT" 60 web

# 5. Initial data (once) and agents.
[ -f "$STATE/seeded" ] || "$SIM_DIR/seed.sh"
"$SIM_DIR/agents/run.sh"

log "up: dashboard http://127.0.0.1:$SIM_WEB_PORT (login in sim/.state/admin.txt), API $SIM_API"
